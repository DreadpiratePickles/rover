package yaml2cedar

import (
	"bytes"
	"strconv"
	"strings"
)

// emit renders the checked rules as Cedar, one policy per rule:
//
//	@id("<rule id>")
//	// from <file>:<line>
//	permit (principal, action == Action::"call_tool", resource == Tool::"server/tool")
//	when { ... };
//
// Every piece of text that comes from the YAML has already been restricted
// to characters that need no escaping; the file name, which comes from the
// operator's command line, is made safe for a // comment by commentSafe.
func emit(p parsed, filename string) []byte {
	var b bytes.Buffer
	b.WriteString("// Generated by `rover policy compile` from " + commentSafe(filename) + ".\n")
	b.WriteString("// Do not edit: edit the YAML and compile again. Rover denies anything no permit allows.\n")
	for _, r := range p.rules {
		b.WriteString("\n")
		emitRule(&b, r, filename)
	}
	return b.Bytes()
}

func emitRule(b *bytes.Buffer, r rule, filename string) {
	b.WriteString(`@id("` + r.id + `")` + "\n")
	if r.implied {
		b.WriteString("// implied: allow rules for " + r.server + " need the agent to see the tool list\n")
		b.WriteString(`permit (principal, action == Action::"list_tools", resource == Server::"` + r.server + `");` + "\n")
		return
	}
	b.WriteString("// from " + commentSafe(filename) + ":" + strconv.Itoa(r.line) + "\n")
	if r.approval {
		b.WriteString(`@rover_require("approval")` + "\n")
	}
	if r.hide {
		b.WriteString(`@rover_hide("true")` + "\n")
	}
	b.WriteString(r.effect() + " (\n  principal,\n  ")
	if r.callOnly() {
		b.WriteString(`action == Action::"call_tool"`)
	} else {
		b.WriteString("action")
	}
	b.WriteString(",\n  ")
	if r.server == "*" {
		b.WriteString("resource")
	} else {
		b.WriteString(`resource == Tool::"` + r.server + "/" + r.tool + `"`)
	}
	b.WriteString("\n)")
	if len(r.conds) > 0 {
		parts := make([]string, len(r.conds))
		for i, c := range r.conds {
			parts[i] = "  " + c.cedar
		}
		b.WriteString("\nwhen {\n" + strings.Join(parts, " &&\n") + "\n}")
	}
	b.WriteString(";\n")
}

// commentSafe replaces anything that could end a // comment (newlines and
// other control or line-separator characters) so a crafted file name cannot
// inject Cedar into the output.
func commentSafe(s string) string {
	return strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f || r == '\u0085' || r == ' ' || r == ' ' {
			return '_'
		}
		return r
	}, s)
}
